-- Higuerote launch pricing guardrails
-- Daytime: calibrated corridors at local market price or a very small discount.
-- Night: existing active multiplier (1.30x from 20:00 to 05:00) is applied.
-- Carro and Camioneta share the same corridor price. Moto remains on its own model.

begin;

create table if not exists public.pricing_corridors (
    id bigint generated by default as identity primary key,
    market text not null,
    origin_label text not null,
    origin_lat double precision not null,
    origin_lng double precision not null,
    origin_radius_km numeric(10,2) not null default 8,
    destination_label text not null,
    destination_aliases text[] not null default '{}'::text[],
    reference_distance_km numeric(10,2) not null,
    distance_tolerance_km numeric(10,2) not null default 8,
    local_day_fare numeric(12,2) not null,
    target_day_fare numeric(12,2) not null,
    vehicle_types text[] not null default array['standard','van']::text[],
    active boolean not null default true,
    note text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (market, destination_label),
    check (origin_radius_km > 0),
    check (reference_distance_km >= 0),
    check (distance_tolerance_km >= 0),
    check (local_day_fare > 0),
    check (target_day_fare > 0),
    check (target_day_fare <= local_day_fare)
);

