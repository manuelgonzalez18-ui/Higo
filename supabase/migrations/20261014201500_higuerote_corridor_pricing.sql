create or replace function public.higo_quote_ride_v5(
    p_pickup_lat double precision,
    p_pickup_lng double precision,
    p_dropoff_lat double precision,
    p_dropoff_lng double precision,
    p_pickup_text text,
    p_dropoff_text text,
    p_vehicle_type text,
    p_service_type text default 'ride',
    p_route_distance_km numeric default null,
    p_route_duration_min numeric default null,
    p_stops_count integer default 0,
    p_promo_code text default null,
    p_user_id uuid default auth.uid(),
    p_client_subtotal_floor numeric default null
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    v_type text := public.higo_canonical_vehicle_type(p_vehicle_type);
    v_base_quote jsonb;
    v_corridor jsonb;
    v_result jsonb;
    v_subtotal numeric;
    v_discount numeric := 0;
    v_final numeric;
    v_multiplier numeric := 1;
    v_corridor_day_fare numeric;
    v_stops_amount numeric := 0;
    v_extras_amount numeric := 0;
    v_minimum_fare numeric := 0;
    v_promo record;
    v_promo_id bigint := null;
    v_resolved_promo_code text := null;
    v_promo_valid boolean := false;
    v_promo_error text := null;
    v_user_uses bigint := 0;
begin
    v_base_quote := public.higo_quote_ride_v4(
        p_pickup_lat,
        p_pickup_lng,
        p_dropoff_lat,
        p_dropoff_lng,
        v_type,
        p_service_type,
        p_route_distance_km,
        p_route_duration_min,
        p_stops_count,
        null,
        p_user_id,
        p_client_subtotal_floor
    );

    v_subtotal := greatest(0, coalesce((v_base_quote->>'subtotal')::numeric, 0));
    v_multiplier := greatest(1, coalesce((v_base_quote->>'surgeMultiplier')::numeric, 1));
    v_stops_amount := greatest(0, coalesce((v_base_quote->>'stopsAmount')::numeric, 0));
    v_extras_amount := greatest(0, coalesce((v_base_quote->>'extrasAmount')::numeric, 0));
    v_minimum_fare := greatest(0, coalesce((v_base_quote->>'minimumFare')::numeric, 0));

    if coalesce(p_service_type, 'ride') = 'ride' and v_type in ('standard','van') then
        v_corridor := public.higo_match_pricing_corridor(
            p_pickup_lat,
            p_pickup_lng,
            p_dropoff_text,
            p_route_distance_km,
            v_type
        );
    end if;

    if v_corridor is not null then
        v_corridor_day_fare := greatest(0, (v_corridor->>'targetDayFare')::numeric);
        v_subtotal := round(
            greatest(
                v_minimum_fare,
                (v_corridor_day_fare + v_stops_amount + v_extras_amount) * v_multiplier
            ),
            2
        );

        v_base_quote := v_base_quote || jsonb_build_object(
            'pricingVersion', 5,
            'pricingModel', 'higuerote_corridor_v1',
            'corridorApplied', true,
            'corridorId', (v_corridor->>'id')::bigint,
            'corridorName', v_corridor->>'destinationLabel',
            'corridorMatchedAlias', v_corridor->>'matchedAlias',
            'corridorReferenceDistanceKm', (v_corridor->>'referenceDistanceKm')::numeric,
            'localReferenceFare', (v_corridor->>'localDayFare')::numeric,
            'corridorDayFare', v_corridor_day_fare,
            'modelSubtotal', v_subtotal,
            'chargedSubtotal', v_subtotal,
            'clientSubtotalFloorApplied', false,
            'corridorOverridesClientFloor', greatest(0, coalesce(p_client_subtotal_floor, 0)) > v_subtotal
        );
    else
        v_base_quote := v_base_quote || jsonb_build_object(
            'corridorApplied', false
        );
    end if;

    if coalesce(trim(p_promo_code), '') <> '' then
        select
            pc.id,
            pc.code,
            pc.discount_type,
            pc.discount_value,
            pc.min_ride_amount,
            pc.expires_at,
            pc.max_uses,
            pc.max_uses_per_user,
            pc.used_count,
            pc.active,
            pc.archived_at,
            pc.budget_amount,
            pc.spent_amount
        into v_promo
        from public.promo_codes pc
        where upper(pc.code) = upper(trim(p_promo_code))
        limit 1;

        if not found then
            v_promo_error := 'inactive';
        else
            v_promo_id := v_promo.id;
            v_resolved_promo_code := v_promo.code;

            if not coalesce(v_promo.active, false)
               or v_promo.archived_at is not null then
                v_promo_error := 'inactive';
            elsif v_promo.expires_at is not null
                  and v_promo.expires_at < now() then
                v_promo_error := 'expired';
            elsif v_subtotal < coalesce(v_promo.min_ride_amount, 0) then
                v_promo_error := 'minimum_not_met';
            elsif v_promo.max_uses is not null
                  and coalesce(v_promo.used_count, 0) >= v_promo.max_uses then
                v_promo_error := 'usage_limit_reached';
            else
                if p_user_id is not null
                   and v_promo.max_uses_per_user is not null then
                    select count(*)
                    into v_user_uses
                    from public.promo_redemptions pr
                    where pr.promo_id = v_promo_id
                      and pr.user_id = p_user_id;
                end if;

                if v_promo.max_uses_per_user is not null
                   and v_user_uses >= v_promo.max_uses_per_user then
                    v_promo_error := 'user_limit_reached';
                else
                    v_discount := case
                        when v_promo.discount_type = 'percent'
                            then v_subtotal * coalesce(v_promo.discount_value, 0) / 100
                        else least(coalesce(v_promo.discount_value, 0), v_subtotal)
                    end;
                    v_discount := round(greatest(0, least(v_discount, v_subtotal)), 2);

                    if v_promo.budget_amount is not null
                       and coalesce(v_promo.spent_amount, 0) + v_discount > v_promo.budget_amount then
                        v_discount := 0;
                        v_promo_error := 'budget_exhausted';
                    else
                        v_promo_valid := true;
                    end if;
                end if;
            end if;
        end if;
    end if;

    v_final := round(greatest(0, v_subtotal - v_discount), 2);

    v_result := v_base_quote || jsonb_build_object(
        'subtotal', v_subtotal,
        'chargedSubtotal', v_subtotal,
        'discount', v_discount,
        'finalPrice', v_final,
        'promoId', case when v_promo_valid then v_promo_id else null end,
        'promoCode', case when v_promo_valid then v_resolved_promo_code else null end,
        'promoValid', v_promo_valid,
        'promoError', v_promo_error,
        'promoDiscountType', case when v_promo_valid then v_promo.discount_type else null end,
        'promoDiscountValue', case when v_promo_valid then v_promo.discount_value else null end,
        'generatedAt', now()
    );

    return v_result;
end;
$$;

