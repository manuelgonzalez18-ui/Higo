create or replace function public.higo_normalize_place_text(p_value text)
returns text
language sql
immutable
as $$
    select trim(
        regexp_replace(
            translate(
                lower(coalesce(p_value, '')),
                'áéíóúüñÁÉÍÓÚÜÑ',
                'aeiouunAEIOUUN'
            ),
            '\s+',
            ' ',
            'g'
        )
    );
$$;

create or replace function public.higo_match_pricing_corridor(
    p_pickup_lat double precision,
    p_pickup_lng double precision,
    p_dropoff_text text,
    p_route_distance_km numeric,
    p_vehicle_type text
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
    v_type text := public.higo_canonical_vehicle_type(p_vehicle_type);
    v_dropoff text := public.higo_normalize_place_text(p_dropoff_text);
    v_result jsonb;
begin
    if p_pickup_lat is null or p_pickup_lng is null or v_dropoff = '' then
        return null;
    end if;

    if v_type not in ('standard','van') then
        return null;
    end if;

    select jsonb_build_object(
        'id', pc.id,
        'market', pc.market,
        'originLabel', pc.origin_label,
        'destinationLabel', pc.destination_label,
        'referenceDistanceKm', pc.reference_distance_km,
        'localDayFare', pc.local_day_fare,
        'targetDayFare', pc.target_day_fare,
        'matchedAlias', matched.alias_text
    )
    into v_result
    from public.pricing_corridors pc
    cross join lateral (
        select a.alias_text
        from unnest(array_append(pc.destination_aliases, pc.destination_label)) a(alias_text)
        where v_dropoff like '%' || public.higo_normalize_place_text(a.alias_text) || '%'
        order by length(public.higo_normalize_place_text(a.alias_text)) desc
        limit 1
    ) matched
    where pc.active = true
      and v_type = any(pc.vehicle_types)
      and public.higo_haversine_km(
            p_pickup_lat,
            p_pickup_lng,
            pc.origin_lat,
            pc.origin_lng
          ) <= pc.origin_radius_km
      and (
          p_route_distance_km is null
          or abs(p_route_distance_km - pc.reference_distance_km) <= pc.distance_tolerance_km
      )
    order by
        abs(coalesce(p_route_distance_km, pc.reference_distance_km) - pc.reference_distance_km) asc,
        length(public.higo_normalize_place_text(matched.alias_text)) desc
    limit 1;

    return v_result;
end;
$$;

