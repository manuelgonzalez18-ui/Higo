create or replace function public.create_ride_request_v5(
    p_client_request_id uuid,
    p_pickup text,
    p_dropoff text,
    p_pickup_lat double precision,
    p_pickup_lng double precision,
    p_dropoff_lat double precision,
    p_dropoff_lng double precision,
    p_vehicle_type text,
    p_service_type text default 'ride',
    p_route_distance_km numeric default null,
    p_route_duration_min numeric default null,
    p_stops jsonb default '[]'::jsonb,
    p_promo_code text default null,
    p_passenger_phone text default null,
    p_delivery_info jsonb default null,
    p_payer text default null,
    p_cod_amount numeric default null,
    p_terms_version text default null,
    p_client_subtotal_floor numeric default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_user_id uuid := auth.uid();
    v_stops_count integer := 0;
    v_quote jsonb;
    v_created jsonb;
    v_ride_id bigint;
    v_replay boolean := false;
    v_result jsonb;
    v_promo public.promo_codes%rowtype;
    v_promo_id bigint;
    v_discount numeric := 0;
begin
    if v_user_id is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;

    if jsonb_typeof(coalesce(p_stops, '[]'::jsonb)) = 'array' then
        v_stops_count := jsonb_array_length(coalesce(p_stops, '[]'::jsonb));
    end if;

    -- Lock promo state before quoting and keep the row locked until redemption.
    if coalesce(trim(p_promo_code), '') <> '' then
        select * into v_promo
        from public.promo_codes pc
        where upper(pc.code) = upper(trim(p_promo_code))
        for update;
    end if;

    v_quote := public.higo_quote_ride_v5(
        p_pickup_lat,
        p_pickup_lng,
        p_dropoff_lat,
        p_dropoff_lng,
        p_pickup,
        p_dropoff,
        p_vehicle_type,
        p_service_type,
        p_route_distance_km,
        p_route_duration_min,
        v_stops_count,
        p_promo_code,
        v_user_id,
        p_client_subtotal_floor
    );

    if coalesce(trim(p_promo_code), '') <> ''
       and not coalesce((v_quote->>'promoValid')::boolean, false) then
        raise exception 'promo_invalid:%', coalesce(v_quote->>'promoError', 'unknown');
    end if;

    -- Create the base ride without promo side effects. The authoritative V5
    -- quote is persisted immediately after creation.
    v_created := public.create_ride_request_v4(
        p_client_request_id,
        p_pickup,
        p_dropoff,
        p_pickup_lat,
        p_pickup_lng,
