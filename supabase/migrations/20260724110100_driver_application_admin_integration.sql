create policy driver_applications_admin_update
on public.driver_applications for update to authenticated
using (public.higo_admin_can('manage_drivers'))
with check (public.higo_admin_can('manage_drivers'));

drop policy if exists driver_application_documents_admin_select on public.driver_application_documents;
create policy driver_application_documents_admin_select
on public.driver_application_documents for select to authenticated
using (public.higo_admin_can('manage_drivers'));

drop policy if exists driver_application_documents_admin_update on public.driver_application_documents;
create policy driver_application_documents_admin_update
on public.driver_application_documents for update to authenticated
using (public.higo_admin_can('manage_drivers'))
with check (public.higo_admin_can('manage_drivers'));

drop policy if exists driver_application_events_admin_select on public.driver_application_events;
create policy driver_application_events_admin_select
on public.driver_application_events for select to authenticated
using (public.higo_admin_can('manage_drivers'));

