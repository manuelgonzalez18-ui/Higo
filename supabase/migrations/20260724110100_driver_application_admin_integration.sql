-- Centralized Higo Driver application workflow.
-- Public submissions are ingested server-to-server; only authorized admins can read PII.

begin;

create extension if not exists pgcrypto;

create table if not exists public.driver_applications (
    id uuid primary key default gen_random_uuid(),
    application_code text not null unique
        check (application_code ~ '^HD-[0-9]{8}-[A-F0-9]{8}$'),
    idempotency_hash text not null unique,
    full_name text not null,
    cedula text not null,
    phone text not null,
    phone_digits text not null,
    email text not null,
    email_hash text not null,
    city text not null,
    vehicle_type text not null check (vehicle_type in ('moto','carro','camioneta')),
    vehicle_brand text not null,
    vehicle_model text not null,
    vehicle_year integer,
    vehicle_color text not null,
    license_plate text not null,
    license_plate_hash text not null,
    status text not null default 'pending_delivery'
        check (status in (
            'pending_delivery','delivery_failed','received','under_review',
            'documents_requested','documents_submitted','correction_requested',
            'approved','converted','waitlist','rejected'
        )),
    status_reason text,
    admin_notes text,
    terms_version text not null,
    privacy_version text not null,
    accept_terms boolean not null default false,
    accept_privacy boolean not null default false,
    accept_contact boolean not null default false,
    source text not null default 'higodriver.com',
    submitted_ip_hash text,
    confirmation_email_sent boolean not null default false,
    converted_user_id uuid references public.profiles(id) on delete set null,
    converted_at timestamptz,
    last_status_changed_at timestamptz not null default now(),
    last_status_changed_by uuid,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists idx_driver_applications_status_created
    on public.driver_applications(status, created_at desc);
create index if not exists idx_driver_applications_email
    on public.driver_applications(lower(email));
create index if not exists idx_driver_applications_vehicle_city
    on public.driver_applications(vehicle_type, city);

create table if not exists public.driver_application_documents (
    id uuid primary key default gen_random_uuid(),
    application_id uuid not null references public.driver_applications(id) on delete cascade,
    document_type text not null check (document_type in (
        'identity','driver_license','vehicle_registration','rcv',
        'vehicle_photo','health_certificate','payment_details','other'
    )),
    file_name text not null,
    mime_type text not null,
    size_bytes bigint not null check (size_bytes > 0 and size_bytes <= 8388608),
    storage_path text not null unique,
    review_status text not null default 'pending'
        check (review_status in ('pending','approved','rejected')),
    review_notes text,
    reviewed_by uuid,
    reviewed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists idx_driver_application_documents_application
    on public.driver_application_documents(application_id, created_at);

create table if not exists public.driver_application_upload_tokens (
    id uuid primary key default gen_random_uuid(),
    application_id uuid not null references public.driver_applications(id) on delete cascade,
    token_hash text not null unique,
    expires_at timestamptz not null,
    used_at timestamptz,
    last_used_at timestamptz,
    created_by uuid,
    created_at timestamptz not null default now()
);

create index if not exists idx_driver_application_upload_tokens_application
    on public.driver_application_upload_tokens(application_id, expires_at desc);

create table if not exists public.driver_application_events (
    id bigint generated by default as identity primary key,
    application_id uuid not null references public.driver_applications(id) on delete cascade,
    actor_type text not null check (actor_type in ('system','admin','applicant')),
    actor_id uuid,
    event_type text not null,
    from_status text,
    to_status text,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

create index if not exists idx_driver_application_events_application
    on public.driver_application_events(application_id, created_at desc);

create or replace function public.higo_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists trg_driver_applications_touch on public.driver_applications;
create trigger trg_driver_applications_touch
before update on public.driver_applications
for each row execute function public.higo_touch_updated_at();

drop trigger if exists trg_driver_application_documents_touch on public.driver_application_documents;
create trigger trg_driver_application_documents_touch
before update on public.driver_application_documents
for each row execute function public.higo_touch_updated_at();

alter table public.driver_applications enable row level security;
alter table public.driver_application_documents enable row level security;
alter table public.driver_application_upload_tokens enable row level security;
alter table public.driver_application_events enable row level security;

drop policy if exists driver_applications_admin_select on public.driver_applications;
create policy driver_applications_admin_select
