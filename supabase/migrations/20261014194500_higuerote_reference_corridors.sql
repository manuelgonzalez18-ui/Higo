-- Higuerote launch reference fares.
-- Goal: for known daytime corridors, Higo Carro/Camioneta should be equal to
-- or slightly below the published local fare. Night pricing still uses the
-- active 1.30x multiplier (20:00-05:00).
--
-- This layer is intentionally limited to passenger Carro/Camioneta and can be
-- disabled per corridor without touching the global distance formula.

create table if not exists public.higuerote_corridor_fares (
    id bigint generated by default as identity primary key,
    name text not null unique,
    aliases text[] not null,
    local_fare numeric(12,2) not null check (local_fare > 0),
    target_fare numeric(12,2) not null check (target_fare > 0),
    active boolean not null default true,
    note text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.higuerote_corridor_fares enable row level security;
drop policy if exists higuerote_corridor_fares_read on public.higuerote_corridor_fares;
create policy higuerote_corridor_fares_read
on public.higuerote_corridor_fares for select
to anon, authenticated
using (active = true);

grant select on public.higuerote_corridor_fares to anon, authenticated;

