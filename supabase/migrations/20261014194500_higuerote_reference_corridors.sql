create or replace function public.higo_normalize_place_label(p_value text)
returns text
language sql
immutable
as $$
    select lower(
        regexp_replace(
            translate(coalesce(p_value,''), 'áéíóúüñÁÉÍÓÚÜÑ', 'aeiouunAEIOUUN'),
            '[^a-zA-Z0-9 ]+', ' ', 'g'
        )
    );
$$;

create or replace function public.higo_higuerote_corridor_match(
    p_dropoff text,
    p_vehicle_type text
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    v_type text := public.higo_canonical_vehicle_type(p_vehicle_type);
    v_norm text := public.higo_normalize_place_label(p_dropoff);
    v_row record;
begin
    if v_type not in ('standard','van') then
        return null;
    end if;

    select f.id, f.name, f.local_fare, f.target_fare, a.alias
      into v_row
      from public.higuerote_corridor_fares f
      cross join lateral unnest(f.aliases) as a(alias)
     where f.active = true
       and v_norm like '%' || public.higo_normalize_place_label(a.alias) || '%'
     order by length(public.higo_normalize_place_label(a.alias)) desc, f.id
     limit 1;

    if not found then
        return null;
    end if;

    return jsonb_build_object(
        'id', v_row.id,
        'name', v_row.name,
        'localFare', v_row.local_fare,
        'targetFare', v_row.target_fare,
        'matchedAlias', v_row.alias
    );
end;
$$;

grant execute on function public.higo_higuerote_corridor_match(text,text) to anon, authenticated;

create or replace function public.higo_quote_ride_v5(
    p_pickup_lat double precision,
    p_pickup_lng double precision,
    p_dropoff_lat double precision,
    p_dropoff_lng double precision,
    p_dropoff text,
    p_vehicle_type text,
    p_service_type text default 'ride',
    p_route_distance_km numeric default null,
    p_route_duration_min numeric default null,
    p_stops_count integer default 0,
    p_promo_code text default null,
    p_user_id uuid default auth.uid(),
    p_client_subtotal_floor numeric default null
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    v_quote jsonb;
    v_match jsonb;
    v_subtotal numeric;
    v_discount numeric := 0;
    v_final numeric;
    v_surge numeric := 1;
    v_target numeric;
    v_stops_amount numeric := 0;
    v_extras_amount numeric := 0;
    v_time_amount numeric := 0;
    v_floor numeric := greatest(0, coalesce(p_client_subtotal_floor, 0));
    v_promo record;
    v_promo_id bigint := null;
    v_resolved_promo_code text := null;
    v_promo_valid boolean := false;
    v_promo_error text := null;
    v_user_uses bigint := 0;
begin
    -- Base authoritative model, without promo. We apply promo after the
    -- corridor reference so minimums/discounts use the price the rider sees.
    v_quote := public.higo_quote_ride_v4(
        p_pickup_lat, p_pickup_lng,
        p_dropoff_lat, p_dropoff_lng,
        p_vehicle_type, p_service_type,
        p_route_distance_km, p_route_duration_min,
        p_stops_count, null, p_user_id, null
    );

    v_match := case
        when coalesce(p_service_type, 'ride') = 'ride'
            then public.higo_higuerote_corridor_match(p_dropoff, p_vehicle_type)
        else null
    end;

    if v_match is not null then
        v_target := (v_match->>'targetFare')::numeric;
        v_surge := greatest(1, coalesce((v_quote->>'surgeMultiplier')::numeric, 1));
        v_stops_amount := greatest(0, coalesce((v_quote->>'stopsAmount')::numeric, 0));
        v_extras_amount := greatest(0, coalesce((v_quote->>'extrasAmount')::numeric, 0));
        v_time_amount := greatest(0, coalesce((v_quote->>'timeAmount')::numeric, 0));
        v_subtotal := round(
            greatest(0, v_target + v_stops_amount + v_extras_amount + v_time_amount) * v_surge,
            2
        );
        -- Deliberadamente ignoramos un client floor más alto cuando una
        -- referencia local conocida aplica; puede venir de un bundle viejo.
    else
        v_subtotal := greatest(
            coalesce((v_quote->>'chargedSubtotal')::numeric, (v_quote->>'subtotal')::numeric, 0),
            v_floor
        );
    end if;

    if coalesce(trim(p_promo_code), '') <> '' then
        select
            pc.id, pc.code, pc.discount_type, pc.discount_value,
            pc.min_ride_amount, pc.expires_at, pc.max_uses,
            pc.max_uses_per_user, pc.used_count, pc.active,
            pc.archived_at, pc.budget_amount, pc.spent_amount
        into v_promo
        from public.promo_codes pc
        where upper(pc.code) = upper(trim(p_promo_code))
        limit 1;

        if not found then
            v_promo_error := 'inactive';
        else
            v_promo_id := v_promo.id;
            v_resolved_promo_code := v_promo.code;
            if not coalesce(v_promo.active, false) or v_promo.archived_at is not null then
                v_promo_error := 'inactive';
            elsif v_promo.expires_at is not null and v_promo.expires_at < now() then
                v_promo_error := 'expired';
            elsif v_subtotal < coalesce(v_promo.min_ride_amount, 0) then
                v_promo_error := 'minimum_not_met';
            elsif v_promo.max_uses is not null and coalesce(v_promo.used_count, 0) >= v_promo.max_uses then
                v_promo_error := 'usage_limit_reached';
            else
                if p_user_id is not null and v_promo.max_uses_per_user is not null then
                    select count(*) into v_user_uses
                    from public.promo_redemptions pr
                    where pr.promo_id = v_promo_id and pr.user_id = p_user_id;
                end if;

                if v_promo.max_uses_per_user is not null and v_user_uses >= v_promo.max_uses_per_user then
                    v_promo_error := 'user_limit_reached';
                else
                    v_discount := case
                        when v_promo.discount_type = 'percent'
                            then v_subtotal * coalesce(v_promo.discount_value, 0) / 100
                        else least(coalesce(v_promo.discount_value, 0), v_subtotal)
                    end;
                    v_discount := round(greatest(0, least(v_discount, v_subtotal)), 2);

                    if v_promo.budget_amount is not null
                       and coalesce(v_promo.spent_amount, 0) + v_discount > v_promo.budget_amount then
                        v_discount := 0;
                        v_promo_error := 'budget_exhausted';
                    else
                        v_promo_valid := true;
                    end if;
                end if;
            end if;
        end if;
    end if;

    v_final := round(greatest(0, v_subtotal - v_discount), 2);

    return v_quote || jsonb_build_object(
        'pricingModel', case when v_match is null
            then coalesce(v_quote->>'pricingModel','distance_time_minimum_v4')
            else 'higuerote_corridor_reference_v1'
        end,
        'corridorApplied', v_match is not null,
        'corridorName', case when v_match is null then null else v_match->>'name' end,
        'corridorLocalFare', case when v_match is null then null else (v_match->>'localFare')::numeric end,
        'corridorTargetDayFare', case when v_match is null then null else (v_match->>'targetFare')::numeric end,
        'subtotal', v_subtotal,
        'chargedSubtotal', v_subtotal,
        'discount', v_discount,
        'finalPrice', v_final,
        'promoId', case when v_promo_valid then v_promo_id else null end,
        'promoCode', case when v_promo_valid then v_resolved_promo_code else null end,
        'promoValid', v_promo_valid,
        'promoError', v_promo_error,
        'promoDiscountType', case when v_promo_valid then v_promo.discount_type else null end,
        'promoDiscountValue', case when v_promo_valid then v_promo.discount_value else null end,
        'clientSubtotalFloor', v_floor,
        'clientSubtotalFloorApplied', case when v_match is null
            then v_floor > coalesce((v_quote->>'chargedSubtotal')::numeric, 0)
            else false
        end,
        'generatedAt', now()
    );
end;
$$;

grant execute on function public.higo_quote_ride_v5(
    double precision,double precision,double precision,double precision,
    text,text,text,numeric,numeric,integer,text,uuid,numeric
) to anon, authenticated;

create or replace function public.create_ride_request_v6(
    p_client_request_id uuid,
    p_pickup text,
    p_dropoff text,
    p_pickup_lat double precision,
    p_pickup_lng double precision,
    p_dropoff_lat double precision,
    p_dropoff_lng double precision,
    p_vehicle_type text,
    p_service_type text default 'ride',
    p_route_distance_km numeric default null,
    p_route_duration_min numeric default null,
    p_stops jsonb default '[]'::jsonb,
    p_promo_code text default null,
    p_passenger_phone text default null,
    p_delivery_info jsonb default null,
    p_payer text default null,
    p_cod_amount numeric default null,
    p_terms_version text default null,
    p_client_subtotal_floor numeric default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_user_id uuid := auth.uid();
    v_stops_count integer := case when jsonb_typeof(coalesce(p_stops,'[]'::jsonb))='array'
        then jsonb_array_length(coalesce(p_stops,'[]'::jsonb)) else 0 end;
    v_quote jsonb;
    v_created jsonb;
    v_ride public.rides%rowtype;
    v_old_discount numeric := 0;
    v_new_discount numeric := 0;
    v_discount_delta numeric := 0;
    v_promo public.promo_codes%rowtype;
    v_result jsonb;
begin
    if v_user_id is null then
        raise exception 'authentication_required' using errcode = '42501';
    end if;

    v_quote := public.higo_quote_ride_v5(
        p_pickup_lat, p_pickup_lng,
        p_dropoff_lat, p_dropoff_lng,
        p_dropoff, p_vehicle_type, p_service_type,
        p_route_distance_km, p_route_duration_min,
        v_stops_count, p_promo_code, v_user_id,
        p_client_subtotal_floor
    );

    if coalesce(trim(p_promo_code),'') <> ''
       and not coalesce((v_quote->>'promoValid')::boolean,false) then
        raise exception 'promo_invalid:%', coalesce(v_quote->>'promoError','unknown');
    end if;

    -- Reuse the proven V5 creation flow for idempotency, terms, promo
    -- redemption and audit creation, then reconcile to the corridor quote.
    v_created := public.create_ride_request_v5(
        p_client_request_id, p_pickup, p_dropoff,
        p_pickup_lat, p_pickup_lng, p_dropoff_lat, p_dropoff_lng,
        p_vehicle_type, p_service_type, p_route_distance_km,
        p_route_duration_min, p_stops, p_promo_code,
        p_passenger_phone, p_delivery_info, p_payer, p_cod_amount,
        p_terms_version, p_client_subtotal_floor
    );

    select * into v_ride
    from public.rides r
    where r.id = (v_created->>'rideId')::bigint
      and r.user_id = v_user_id
    for update;

    if not found then
        raise exception 'ride_creation_failed';
    end if;

    v_old_discount := coalesce(v_ride.discount_amount,0);
    v_new_discount := greatest(0, coalesce((v_quote->>'discount')::numeric,0));
    v_discount_delta := v_new_discount - v_old_discount;

    if v_ride.promo_code_id is not null and v_discount_delta <> 0 then
        select * into v_promo
        from public.promo_codes pc
        where pc.id = v_ride.promo_code_id
        for update;

        if v_promo.budget_amount is not null
           and coalesce(v_promo.spent_amount,0) + v_discount_delta > v_promo.budget_amount then
            raise exception 'promo_invalid:budget_exhausted';
        end if;

        update public.promo_codes
        set spent_amount = greatest(0, coalesce(spent_amount,0) + v_discount_delta)
        where id = v_promo.id;

        update public.promo_redemptions
        set discount_amount = v_new_discount
        where ride_id = v_ride.id;
    end if;

    update public.rides r
    set quoted_distance_km = coalesce((v_quote->>'distanceKm')::numeric, r.quoted_distance_km),
        quoted_duration_min = coalesce((v_quote->>'durationMin')::numeric, r.quoted_duration_min),
        pricing_version = coalesce((v_quote->>'pricingVersion')::integer, r.pricing_version),
        pricing_model = coalesce(v_quote->>'pricingModel', r.pricing_model),
        pricing_multiplier = coalesce((v_quote->>'surgeMultiplier')::numeric, r.pricing_multiplier),
        pricing_multiplier_reason = coalesce(v_quote->>'multiplierReason', r.pricing_multiplier_reason),
        pricing_base_amount = coalesce((v_quote->>'base')::numeric, r.pricing_base_amount),
        pricing_distance_amount = coalesce((v_quote->>'distanceAmount')::numeric, r.pricing_distance_amount),
        pricing_time_amount = coalesce((v_quote->>'timeAmount')::numeric, r.pricing_time_amount),
        pricing_stops_amount = coalesce((v_quote->>'stopsAmount')::numeric, r.pricing_stops_amount),
        pricing_extras_amount = coalesce((v_quote->>'extrasAmount')::numeric, r.pricing_extras_amount),
        pricing_minimum_fare = coalesce((v_quote->>'minimumFare')::numeric, r.pricing_minimum_fare),
        price_before_discount = (v_quote->>'subtotal')::numeric,
        discount_amount = v_new_discount,
        price = (v_quote->>'finalPrice')::numeric,
        pricing_snapshot = v_quote
    where r.id = v_ride.id;

    update public.pricing_quote_audit
    set rollout_mode = coalesce(v_quote->>'rolloutMode', rollout_mode),
        model_applied = coalesce((v_quote->>'modelApplied')::boolean, model_applied),
        pilot_bucket = coalesce((v_quote->>'pilotBucket')::integer, pilot_bucket),
        distance_km = coalesce((v_quote->>'distanceKm')::numeric, distance_km),
        duration_min = coalesce((v_quote->>'durationMin')::numeric, duration_min),
        legacy_subtotal = coalesce((v_quote->>'legacySubtotal')::numeric, legacy_subtotal),
        model_subtotal = coalesce((v_quote->>'modelSubtotal')::numeric, model_subtotal),
        charged_subtotal = (v_quote->>'subtotal')::numeric,
        quote = v_quote
    where ride_id = v_ride.id;

    select jsonb_build_object(
        'rideId', r.id,
        'price', r.price,
        'status', r.status,
        'quote', r.pricing_snapshot,
        'idempotentReplay', coalesce((v_created->>'idempotentReplay')::boolean,false)
    )
    into v_result
    from public.rides r
    where r.id = v_ride.id;

    return v_result;
end;
$$;

