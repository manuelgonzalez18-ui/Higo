create or replace function public.admin_change_profile_role(p_user_id uuid, p_role text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare v_before jsonb;
begin
    perform public.higo_assert_admin('manage_users', true);
    if public.higo_admin_role()<>'super_admin' then raise exception 'super_admin_required'; end if;
    if p_role not in ('passenger','user','driver','admin','merchant') then raise exception 'invalid_profile_role'; end if;
    if p_user_id=auth.uid() and p_role<>'admin' then raise exception 'cannot_demote_self'; end if;
    select to_jsonb(p) into v_before from public.profiles p where id=p_user_id for update;
    update public.profiles set role=p_role where id=p_user_id;
    if p_role='admin' then
        insert into public.admin_staff_roles(user_id,staff_role) values(p_user_id,'viewer') on conflict(user_id) do nothing;
    end if;
    insert into public.admin_audit_log(actor_id,action,entity_type,entity_id,before_data,after_data)
    select auth.uid(),'profile.role_change','profile',p_user_id::text,v_before,to_jsonb(p) from public.profiles p where p.id=p_user_id;
end;
$$;

create or replace function public.higo_audit_row()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_before jsonb := case when tg_op in ('UPDATE','DELETE') then to_jsonb(old) else null end;
    v_after jsonb := case when tg_op in ('INSERT','UPDATE') then to_jsonb(new) else null end;
    v_id text := coalesce(v_after->>'id', v_before->>'id', v_after->>'user_id', v_before->>'user_id');
begin
    if auth.uid() is not null then
        insert into public.admin_audit_log(actor_id,action,entity_type,entity_id,before_data,after_data,metadata)
        values(auth.uid(),lower(tg_op),tg_table_name,v_id,v_before,v_after,jsonb_build_object('schema',tg_table_schema));
    end if;
    return coalesce(new,old);
end;
$$;

do $$
declare t text;
begin
    foreach t in array array['pricing_config','pricing_rules','promo_codes','coverage_zones'] loop
        if to_regclass('public.'||t) is not null then
            execute format('drop trigger if exists trg_higo_audit_%I on public.%I',t,t);
            execute format('create trigger trg_higo_audit_%I after insert or update or delete on public.%I for each row execute function public.higo_audit_row()',t,t);
        end if;
    end loop;
end $$;

