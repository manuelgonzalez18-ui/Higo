    ('car-monthly', 'Carro mensual', 'standard', 'monthly', 30, 20),
    ('van-weekly', 'Camioneta semanal', 'van', 'weekly', 7, 7),
    ('van-monthly', 'Camioneta mensual', 'van', 'monthly', 30, 25)
