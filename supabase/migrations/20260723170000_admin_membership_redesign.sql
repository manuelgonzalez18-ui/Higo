create or replace function public.admin_business_analytics(
    p_days integer default 30
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    v_days integer := greatest(7, least(coalesce(p_days, 30), 365));
    v_since timestamptz;
    v_revenue numeric := 0;
    v_payers bigint := 0;
    v_payments bigint := 0;
    v_renewing bigint := 0;
    v_membership_daily jsonb := '[]'::jsonb;
    v_trip_daily jsonb := '[]'::jsonb;
begin
    v_since := date_trunc('day', now()) - (v_days - 1) * interval '1 day';

    perform public.higo_assert_admin('view_analytics');

    select
        coalesce(sum(amount), 0),
        count(*),
        count(distinct driver_id)
    into
        v_revenue,
        v_payments,
        v_payers
    from public.driver_memberships
    where voided_at is null
      and paid_at >= v_since;

    select count(*)
    into v_renewing
    from (
        select driver_id
        from public.driver_memberships
        where voided_at is null
          and paid_at >= v_since
        group by driver_id
        having count(*) > 1
    ) as renewing_drivers;

    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'day', gs.bucket_day::date,
                'revenue', coalesce(md.revenue, 0),
                'payments', coalesce(md.payments, 0)
            )
            order by gs.bucket_day
        ),
        '[]'::jsonb
    )
    into v_membership_daily
    from generate_series(
        v_since,
        date_trunc('day', now()),
        interval '1 day'
    ) as gs(bucket_day)
    left join (
        select
            date_trunc('day', paid_at) as bucket_day,
            sum(amount) as revenue,
            count(*) as payments
        from public.driver_memberships
        where voided_at is null
          and paid_at >= v_since
        group by date_trunc('day', paid_at)
    ) as md
        on md.bucket_day = gs.bucket_day;

    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'day', gs.bucket_day::date,
                'volume', coalesce(td.volume, 0),
                'rides', coalesce(td.rides, 0)
            )
            order by gs.bucket_day
        ),
        '[]'::jsonb
    )
    into v_trip_daily
    from generate_series(
        v_since,
        date_trunc('day', now()),
        interval '1 day'
    ) as gs(bucket_day)
    left join (
        select
            date_trunc('day', created_at) as bucket_day,
            sum(
                case
                    when payment_confirmed_at is not null then price
                    else 0
                end
            ) as volume,
            count(*) as rides
        from public.rides
        where created_at >= v_since
        group by date_trunc('day', created_at)
    ) as td
        on td.bucket_day = gs.bucket_day;

    return jsonb_build_object(
        'days', v_days,
        'membershipRevenue', v_revenue,
        'payments', v_payments,
        'payingDrivers', v_payers,
        'averageRevenuePerDriver',
            case when v_payers > 0 then round(v_revenue / v_payers, 2) else 0 end,
        'renewalRate',
            case when v_payers > 0 then round((v_renewing::numeric / v_payers::numeric) * 100, 1) else 0 end,
        'activeMemberships',
            (
                select count(*)
                from public.admin_driver_membership_status
                where membership_state in ('active','expiring_soon','grace_period')
            ),
        'tripVolume',
            coalesce(
                (
                    select sum(price)
                    from public.rides
                    where created_at >= v_since
                      and payment_confirmed_at is not null
                ),
                0
            ),
        'rides',
            (
                select count(*)
                from public.rides
                where created_at >= v_since
            ),
        'membershipDaily', v_membership_daily,
        'tripDaily', v_trip_daily,
        'generatedAt', now()
    );
end;
$$;

create or replace function public.admin_list_drivers(
    p_query text default null,
    p_state text default 'all',
    p_limit integer default 50,
    p_offset integer default 0
)
returns setof public.admin_driver_membership_status
language plpgsql
stable
security definer
set search_path = public
as $$
begin
    perform public.higo_assert_admin('view_dashboard');
    return query
    select * from public.admin_driver_membership_status d
    where (coalesce(trim(p_query),'') = '' or
           d.full_name ilike '%' || trim(p_query) || '%' or
           d.phone ilike '%' || trim(p_query) || '%' or
           d.license_plate ilike '%' || trim(p_query) || '%' or
           d.payment_reference ilike '%' || trim(p_query) || '%')
      and (p_state = 'all' or d.membership_state = p_state)
    order by
        case d.membership_state when 'expired' then 1 when 'no_membership' then 2 when 'expiring_soon' then 3 else 4 end,
        d.expires_at nulls first,
        d.created_at desc
    limit greatest(1, least(coalesce(p_limit,50),200))
    offset greatest(coalesce(p_offset,0),0);
end;
$$;

create or replace function public.higo_sync_driver_membership(p_driver_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_active boolean;
    v_last_payment timestamptz;
begin
    select exists(
        select 1 from public.driver_memberships
        where driver_id = p_driver_id and voided_at is null and status='active' and expires_at >= now()
    ), max(paid_at) filter (where voided_at is null)
    into v_active, v_last_payment
    from public.driver_memberships where driver_id = p_driver_id;

    update public.profiles
       set subscription_status = case when v_active then 'active' else 'suspended' end,
           last_payment_date = v_last_payment
     where id = p_driver_id and role='driver';
end;
$$;

create or replace function public.admin_record_driver_membership(
    p_driver_id uuid,
    p_plan_id uuid,
    p_payment_method text,
    p_payment_reference text default null,
    p_notes text default null,
    p_amount numeric default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
    v_plan public.driver_membership_plans%rowtype;
    v_id bigint;
    v_start timestamptz := now();
    v_expires timestamptz;
begin
    perform public.higo_assert_admin('manage_memberships', true);
    select * into v_plan from public.driver_membership_plans where id=p_plan_id and active;
    if not found then raise exception 'membership_plan_not_found'; end if;
    if not exists(select 1 from public.profiles where id=p_driver_id and role='driver' and archived_at is null) then
        raise exception 'driver_not_found_or_archived';
    end if;
    v_expires := v_start + make_interval(days => v_plan.duration_days);
    insert into public.driver_memberships(
        driver_id, plan_id, plan, amount, currency, period, paid_at, expires_at,
        status, payment_method, payment_reference, notes, created_by
    ) values (
        p_driver_id, v_plan.id, v_plan.code, coalesce(p_amount, v_plan.amount), v_plan.currency,
        v_plan.period, v_start, v_expires, 'active', nullif(trim(p_payment_method),''),
        nullif(trim(p_payment_reference),''), nullif(trim(p_notes),''), auth.uid()
    ) returning id into v_id;
    perform public.higo_sync_driver_membership(p_driver_id);
    insert into public.admin_audit_log(actor_id, action, entity_type, entity_id, after_data)
    values(auth.uid(),'membership.record','driver_membership',v_id::text,
        jsonb_build_object('driver_id',p_driver_id,'plan_id',p_plan_id,'amount',coalesce(p_amount,v_plan.amount),'expires_at',v_expires));
    return v_id;
end;
$$;

create or replace function public.admin_void_driver_membership(p_membership_id bigint, p_reason text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_driver uuid;
    v_before jsonb;
begin
    perform public.higo_assert_admin('manage_memberships', true);
    if coalesce(trim(p_reason),'') = '' then raise exception 'void_reason_required'; end if;
    select driver_id, to_jsonb(dm) into v_driver, v_before
      from public.driver_memberships dm where id=p_membership_id and voided_at is null for update;
    if v_driver is null then raise exception 'membership_not_found'; end if;
    update public.driver_memberships
       set status='voided', voided_at=now(), voided_by=auth.uid(), void_reason=trim(p_reason), updated_at=now()
     where id=p_membership_id;
    perform public.higo_sync_driver_membership(v_driver);
    insert into public.admin_audit_log(actor_id, action, entity_type, entity_id, before_data, reason)
    values(auth.uid(),'membership.void','driver_membership',p_membership_id::text,v_before,trim(p_reason));
end;
$$;

create or replace function public.admin_set_driver_exception(
    p_driver_id uuid,
    p_action text,
    p_reason text,
    p_until timestamptz default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare v_before jsonb;
begin
    perform public.higo_assert_admin('manage_drivers', true);
    if coalesce(trim(p_reason),'')='' then raise exception 'reason_required'; end if;
    select to_jsonb(p) into v_before from public.profiles p where id=p_driver_id and role='driver' for update;
    if v_before is null then raise exception 'driver_not_found'; end if;
    if p_action='suspend' then
        update public.profiles set subscription_status='suspended', suspended_at=now(), suspension_reason=trim(p_reason) where id=p_driver_id;
    elsif p_action='grace' then
        if p_until is null or p_until <= now() then raise exception 'future_until_required'; end if;
        update public.profiles set subscription_override_until=p_until, suspended_at=null, suspension_reason=null where id=p_driver_id;
    elsif p_action='clear' then
        update public.profiles set subscription_override_until=null, suspended_at=null, suspension_reason=null where id=p_driver_id;
        perform public.higo_sync_driver_membership(p_driver_id);
    else
        raise exception 'invalid_driver_action';
    end if;
    insert into public.admin_audit_log(actor_id, action, entity_type, entity_id, before_data, after_data, reason)
    select auth.uid(),'driver.'||p_action,'profile',p_driver_id::text,v_before,to_jsonb(p),trim(p_reason)
      from public.profiles p where p.id=p_driver_id;
end;
$$;

