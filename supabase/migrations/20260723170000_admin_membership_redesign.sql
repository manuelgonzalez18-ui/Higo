-- Higo admin redesign: membership-first finance, audit, permissions and aggregated metrics.
-- Safe rollout: MFA enforcement defaults OFF until all admins enroll a verified factor.

begin;

create extension if not exists pgcrypto;

create table if not exists public.driver_membership_plans (
    id uuid primary key default gen_random_uuid(),
    code text not null unique,
    name text not null,
    vehicle_type text,
    period text not null check (period in ('weekly','monthly','yearly')),
    duration_days integer not null check (duration_days > 0),
    amount numeric(12,2) not null check (amount >= 0),
    currency text not null default 'USD',
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

insert into public.driver_membership_plans (code, name, vehicle_type, period, duration_days, amount)
values
    ('moto-weekly', 'Moto semanal', 'moto', 'weekly', 7, 3),
    ('moto-monthly', 'Moto mensual', 'moto', 'monthly', 30, 10),
