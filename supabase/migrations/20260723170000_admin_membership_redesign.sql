create index if not exists idx_admin_audit_log_entity on public.admin_audit_log(entity_type, entity_id);

create or replace function public.higo_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1 from public.profiles p
        where p.id = auth.uid() and p.role = 'admin'
    );
$$;

create or replace function public.higo_admin_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
    select coalesce((
        select r.staff_role
        from public.admin_staff_roles r
        where r.user_id = auth.uid() and r.active
    ), case when public.higo_is_admin() then 'viewer' else null end);
$$;

create or replace function public.higo_admin_can(p_permission text)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    v_role text := public.higo_admin_role();
begin
    if v_role is null then return false; end if;
    if v_role = 'super_admin' then return true; end if;
    if p_permission in ('view_dashboard','view_analytics') then return true; end if;
    if v_role = 'operations' and p_permission in ('manage_drivers','manage_operations','manage_pricing','manage_zones','manage_disputes') then return true; end if;
    if v_role = 'support' and p_permission in ('manage_support','manage_disputes','view_users') then return true; end if;
    if v_role = 'finance' and p_permission in ('manage_memberships','view_finance','manage_disputes') then return true; end if;
    if v_role = 'viewer' and p_permission in ('view_users') then return true; end if;
    return false;
end;
$$;

create or replace function public.higo_assert_admin(p_permission text, p_sensitive boolean default false)
returns void
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    v_require_mfa boolean := false;
    v_aal text := coalesce(auth.jwt()->>'aal', 'aal1');
begin
    if not public.higo_admin_can(p_permission) then
        raise exception 'admin_permission_denied' using errcode = '42501';
    end if;
    select require_mfa into v_require_mfa from public.admin_security_settings where singleton;
    if p_sensitive and v_require_mfa and v_aal <> 'aal2' then
        raise exception 'admin_mfa_required' using errcode = '42501';
    end if;
end;
$$;

create or replace function public.admin_get_context()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
    v_role text;
    v_require_mfa boolean;
begin
    if not public.higo_is_admin() then
        return jsonb_build_object('authorized', false);
    end if;
    v_role := public.higo_admin_role();
    select require_mfa into v_require_mfa from public.admin_security_settings where singleton;
    return jsonb_build_object(
        'authorized', true,
        'user_id', auth.uid(),
        'staff_role', v_role,
        'require_mfa', coalesce(v_require_mfa, false),
        'aal', coalesce(auth.jwt()->>'aal', 'aal1'),
        'permissions', jsonb_build_object(
            'manage_memberships', public.higo_admin_can('manage_memberships'),
            'manage_drivers', public.higo_admin_can('manage_drivers'),
            'manage_support', public.higo_admin_can('manage_support'),
            'manage_operations', public.higo_admin_can('manage_operations'),
            'manage_users', v_role = 'super_admin',
            'manage_security', v_role = 'super_admin'
        )
    );
end;
$$;

create or replace function public.higo_membership_status(
    p_expires_at timestamptz,
    p_membership_status text,
    p_archived_at timestamptz,
    p_suspended_at timestamptz,
    p_override_until timestamptz
)
returns text
language sql
stable
as $$
    select case
        when p_archived_at is not null then 'archived'
        when p_suspended_at is not null then 'suspended'
        when p_override_until is not null and p_override_until >= now() then 'grace_period'
        when p_membership_status is null then 'no_membership'
        when p_membership_status <> 'active' then p_membership_status
        when p_expires_at < now() then 'expired'
        when p_expires_at <= now() + interval '7 days' then 'expiring_soon'
        else 'active'
    end;
$$;

create or replace view public.admin_driver_membership_status as
select
    p.id,
    p.full_name,
    p.phone,
    p.email,
    p.avatar_url,
    p.vehicle_type,
    p.vehicle_brand,
    p.vehicle_model,
    p.vehicle_color,
    p.license_plate,
    p.status as online_status,
    p.updated_at as location_updated_at,
    p.subscription_status,
    p.last_payment_date,
    p.suspended_at,
    p.suspension_reason,
    p.archived_at,
    p.archive_reason,
    p.subscription_override_until,
    p.created_at,
    m.id as membership_id,
    m.plan_id,
    coalesce(mp.name, m.plan) as membership_plan,
    m.amount as membership_amount,
    m.currency,
    m.period,
    m.paid_at,
    m.expires_at,
    m.payment_method,
    m.payment_reference,
    public.higo_membership_status(
        m.expires_at, m.status, p.archived_at, p.suspended_at, p.subscription_override_until
    ) as membership_state
from public.profiles p
left join lateral (
    select dm.*
    from public.driver_memberships dm
    where dm.driver_id = p.id and dm.voided_at is null
    order by dm.expires_at desc, dm.paid_at desc
    limit 1
) m on true
left join public.driver_membership_plans mp on mp.id = m.plan_id
where p.role = 'driver';

