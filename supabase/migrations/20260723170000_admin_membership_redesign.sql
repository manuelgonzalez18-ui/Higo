create table if not exists public.driver_memberships (
    id bigint generated by default as identity primary key,
    driver_id uuid not null references public.profiles(id) on delete restrict,
    plan text,
    amount numeric(12,2) not null default 0,
    period text,
    paid_at timestamptz not null default now(),
    expires_at timestamptz not null,
    status text not null default 'active'
);

alter table public.driver_memberships
    add column if not exists plan_id uuid references public.driver_membership_plans(id),
    add column if not exists currency text not null default 'USD',
    add column if not exists payment_method text,
    add column if not exists payment_reference text,
    add column if not exists notes text,
    add column if not exists receipt_url text,
    add column if not exists created_by uuid,
    add column if not exists voided_at timestamptz,
    add column if not exists voided_by uuid,
    add column if not exists void_reason text,
    add column if not exists updated_at timestamptz not null default now();

alter table public.profiles
    add column if not exists archived_at timestamptz,
    add column if not exists archived_by uuid,
    add column if not exists archive_reason text,
    add column if not exists suspension_reason text,
    add column if not exists subscription_override_until timestamptz;

create index if not exists idx_driver_memberships_driver_expires
    on public.driver_memberships(driver_id, expires_at desc)
    where voided_at is null;
create index if not exists idx_driver_memberships_paid_at
    on public.driver_memberships(paid_at desc)
    where voided_at is null;
create unique index if not exists idx_driver_memberships_payment_reference
    on public.driver_memberships(payment_reference)
    where payment_reference is not null and voided_at is null;

create table if not exists public.admin_staff_roles (
    user_id uuid primary key references public.profiles(id) on delete cascade,
    staff_role text not null default 'viewer'
        check (staff_role in ('super_admin','operations','support','finance','viewer')),
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    updated_by uuid
);

insert into public.admin_staff_roles (user_id, staff_role)
