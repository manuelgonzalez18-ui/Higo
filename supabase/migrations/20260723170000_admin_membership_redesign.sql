create or replace function public.admin_update_staff_role(p_user_id uuid, p_staff_role text, p_active boolean default true)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    perform public.higo_assert_admin('manage_users', true);
    if public.higo_admin_role() <> 'super_admin' then raise exception 'super_admin_required'; end if;
    if p_staff_role not in ('super_admin','operations','support','finance','viewer') then raise exception 'invalid_staff_role'; end if;
    if p_user_id=auth.uid() and (p_staff_role<>'super_admin' or not p_active) then raise exception 'cannot_demote_self'; end if;
    insert into public.admin_staff_roles(user_id,staff_role,active,updated_by)
    values(p_user_id,p_staff_role,p_active,auth.uid())
    on conflict(user_id) do update set staff_role=excluded.staff_role, active=excluded.active, updated_at=now(), updated_by=auth.uid();
    insert into public.admin_audit_log(actor_id,action,entity_type,entity_id,after_data)
    values(auth.uid(),'admin.staff_role','admin_staff_role',p_user_id::text,jsonb_build_object('staff_role',p_staff_role,'active',p_active));
end;
$$;

